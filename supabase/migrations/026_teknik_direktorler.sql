begin;

create table public.teknik_direktorler (
    id uuid primary key default gen_random_uuid(),
    sira smallint not null unique,
    isim text not null,
    ulke text not null,
    transfermarkt_id varchar not null unique,   -- Transfermarkt'ın teknik direktör ID'si (oyuncu ID'sinden farklıdır)
    dogum_tarihi date,
    foto_url text,
    yeni_nesil boolean not null default false
);

create table public.teknik_direktor_takimlari (
    teknik_direktor_id uuid not null references public.teknik_direktorler (id) on delete cascade,
    sira smallint not null,
    takim_isim text not null,
    milli boolean not null default false,
    kulup_id uuid references public.kulupler (id),
    primary key (teknik_direktor_id, sira)
);

create index teknik_direktor_takimlari_kulup_idx on public.teknik_direktor_takimlari (kulup_id);

